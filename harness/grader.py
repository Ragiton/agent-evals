#!/usr/bin/env python3
"""Deterministic grader for engineering-agent run workspaces.

The grader deliberately has no LLM component.  It reads an eval YAML file and
an already completed workspace, runs the checks required by that fixture, and
writes a machine-readable ``results.json``.  KiCad checks are generated by the
grader when a schematic or PCB is configured; fixture-provided deterministic
checks are also executed verbatim (apart from the legacy KiCad ``--exit-code``
flag, which is normalized to KiCad's real ``--exit-code-violations`` flag).

Examples::

    python harness/grader.py --run results/runs/run-001
    python harness/grader.py --spec evals/foo.yaml --workspace /tmp/run \
        --output /tmp/run/results.json

The input forms are intentionally both supported.  ``--run`` is convenient for
this repository's run.json manifests, while ``--spec`` + ``--workspace`` makes
the grader usable with standalone fixtures and tests.
"""
from __future__ import annotations

import argparse
import datetime
import glob as _glob
import json
import os
import pathlib
import re
import shlex
import subprocess
import sys
from collections.abc import Iterable, Mapping
from typing import Any

try:
    import yaml
except ImportError:  # pragma: no cover - only exercised in minimal installs
    yaml = None


SCHEMA_VERSION = "1.0.0"
DEFAULT_TIMEOUT_SECONDS = 300
MAX_OUTPUT_BYTES = 10 * 1024 * 1024


# ---------------------------------------------------------------------------
# Small, deterministic filesystem/spec helpers


def _as_path(value: Any) -> pathlib.Path | None:
    if value is None:
        return None
    if isinstance(value, pathlib.Path):
        return value
    if isinstance(value, (str, os.PathLike)):
        return pathlib.Path(value)
    return None


def _safe_relpath(path: pathlib.Path, root: pathlib.Path) -> str:
    """Return a stable POSIX path, preferring paths relative to *root*."""
    try:
        return path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return path.as_posix()


def _unique_paths(paths: Iterable[pathlib.Path]) -> list[pathlib.Path]:
    result: list[pathlib.Path] = []
    seen: set[str] = set()
    for path in paths:
        key = str(path.resolve(strict=False))
        if key not in seen:
            result.append(path)
            seen.add(key)
    return result


def _glob_matches(workspace: pathlib.Path, pattern: str) -> list[pathlib.Path]:
    """Expand a workspace-relative file/directory pattern deterministically."""
    raw = pathlib.Path(pattern)
    if raw.is_absolute():
        matches = [pathlib.Path(value) for value in _glob.glob(str(raw), recursive=True)]
    else:
        matches = list(workspace.glob(str(raw)))
    return _unique_paths(sorted(matches))


def _canonical_matches(matches: list[pathlib.Path]) -> list[pathlib.Path]:
    """Prefer a canonical KiCad file over agent scratch/debug attempts."""
    if not matches:
        return []
    canonical = [
        path for path in matches
        if not path.name.startswith("_") and "nolib" not in path.name.lower()
    ]
    return sorted(canonical or matches)


def _first_existing(value: Any, workspace: pathlib.Path) -> tuple[pathlib.Path | None, bool]:
    """Resolve a fixture input and return (path, was_configured).

    ``was_configured`` distinguishes an absent optional input (which is
    skipped) from a fixture that explicitly names a missing file (which must
    fail as a check).
    """
    if value is None:
        return None, False
    if isinstance(value, (list, tuple)):
        configured = bool(value)
        candidates = list(value)
    else:
        configured = True
        candidates = [value]

    for candidate in candidates:
        path = _as_path(candidate)
        if path is None:
            continue
        matches = _canonical_matches(_glob_matches(workspace, str(path)))
        if matches:
            return matches[0], configured
    # Preserve the requested path for a useful missing-file reason.
    first = _as_path(candidates[0]) if candidates else None
    if first is not None and not first.is_absolute():
        first = workspace / first
    return first, configured


def _mapping(value: Any) -> Mapping[str, Any]:
    return value if isinstance(value, Mapping) else {}


def _output_patterns(spec: Mapping[str, Any]) -> list[str]:
    """Collect required output patterns from the supported fixture shapes."""
    patterns: list[str] = []

    def add(value: Any) -> None:
        if isinstance(value, str):
            patterns.append(value)
        elif isinstance(value, Mapping):
            path = value.get("path", value.get("pattern", value.get("file")))
            required = value.get("required", True)
            if path is not None and required is not False:
                add(path)
        elif isinstance(value, (list, tuple)):
            for item in value:
                add(item)

    add(spec.get("required_files"))
    add(_mapping(spec.get("fixture")).get("required_files"))
    add(_mapping(spec.get("fixtures")).get("required_files"))
    grading = _mapping(spec.get("grading"))
    add(grading.get("required_files"))
    add(_mapping(grading.get("fixture")).get("required_files"))
    add(spec.get("outputs"))
    add(_mapping(spec.get("fixture")).get("outputs"))
    add(_mapping(spec.get("fixtures")).get("outputs"))
    return list(dict.fromkeys(patterns))


def _input_values(spec: Mapping[str, Any], kind: str) -> tuple[Any, bool]:
    """Find a schematic/PCB value across common fixture schema variants."""
    keys = {
        "schematic": ("schematic", "kicad_sch", "sch", "erc_input"),
        "pcb": ("pcb", "kicad_pcb", "board", "drc_input"),
    }[kind]
    containers: list[Mapping[str, Any]] = [
        _mapping(spec.get("inputs")),
        _mapping(spec.get("kicad")),
        _mapping(spec.get("fixture")),
        _mapping(spec.get("fixtures")),
        _mapping(_mapping(spec.get("fixture")).get("inputs")),
        _mapping(_mapping(spec.get("fixtures")).get("inputs")),
        _mapping(_mapping(spec.get("grading")).get("inputs")),
        _mapping(_mapping(spec.get("grading")).get("kicad")),
        _mapping(_mapping(spec.get("grading")).get("fixture")),
    ]
    for container in containers:
        for key in keys:
            if key in container:
                return container[key], True

    # A deterministic check may carry its own input, which is useful for
    # fixtures containing more than one board or schematic.
    for check in _deterministic_specs(spec):
        if not isinstance(check, Mapping):
            continue
        check_type = _classify_check(check)
        if check_type != kind and not (kind == "schematic" and check_type == "erc") and not (
            kind == "pcb" and check_type in {"drc", "gerber_export"}
        ):
            continue
        for key in ("input", "file", "path", "input_file"):
            if key in check:
                return check[key], True

    # Outputs are a contract too.  If a fixture names a .kicad_sch/.kicad_pcb
    # output but no explicit input, that output is the KiCad input.
    suffix = ".kicad_sch" if kind == "schematic" else ".kicad_pcb"
    for pattern in _output_patterns(spec):
        if suffix in pattern:
            return pattern, True
    return None, False


def _resolve_inputs(spec: Mapping[str, Any], workspace: pathlib.Path) -> dict[str, tuple[pathlib.Path | None, bool]]:
    resolved: dict[str, tuple[pathlib.Path | None, bool]] = {}
    for kind in ("schematic", "pcb"):
        value, configured = _input_values(spec, kind)
        path, resolved_configured = _first_existing(value, workspace)
        resolved[kind] = (path, configured or resolved_configured)
    return resolved


def _deterministic_specs(spec: Mapping[str, Any]) -> list[Mapping[str, Any]]:
    grading = _mapping(spec.get("grading"))
    raw = grading.get("deterministic", [])
    if not isinstance(raw, list):
        return []
    return [item for item in raw if isinstance(item, Mapping)]


def _classify_check(check: Mapping[str, Any]) -> str:
    explicit = str(check.get("type", check.get("kind", ""))).strip().lower().replace("-", "_")
    aliases = {
        "required": "required_files",
        "required_file": "required_files",
        "files": "required_files",
        "file_presence": "required_files",
        "schematic_erc": "erc",
        "electrical_rules_check": "erc",
        "pcb_drc": "drc",
        "design_rules_check": "drc",
        "gerbers": "gerber_export",
        "gerber": "gerber_export",
        "pcb_gerbers": "gerber_export",
        "gerber_export": "gerber_export",
    }
    if explicit in aliases:
        return aliases[explicit]
    if explicit in {"erc", "drc", "generic", "deterministic", "required_files"}:
        return explicit

    name = str(check.get("name", "")).lower()
    command = str(check.get("command", "")).lower()
    combined = f"{name} {command}"
    if "sch erc" in combined or "erc" in name:
        return "erc"
    if "pcb drc" in combined or "drc" in name:
        return "drc"
    # Only a real KiCad export command satisfies the export requirement.  A
    # shell check named gerbers_exported is still a useful additional check,
    # but it does not replace the required command invocation.
    if "pcb export gerbers" in combined:
        return "gerber_export"
    if "required" in name and "file" in name:
        return "required_files"
    return "generic"


def _normalize_kicad_command(command: str) -> str:
    """Fix the KiCad 8/9 legacy flag without changing other fixture commands."""
    if "kicad-cli" not in command:
        return command
    if not re.search(r"\bkicad-cli\s+(?:sch\s+erc|pcb\s+drc)\b", command):
        return command
    return re.sub(r"(?<![\w-])--exit-code(?!-violations)", "--exit-code-violations", command)


def _placeholder_path(
    token: str,
    workspace: pathlib.Path,
    inputs: Mapping[str, tuple[pathlib.Path | None, bool]],
    gerber_dir: pathlib.Path,
) -> tuple[str | None, str | None]:
    if token in {"{kicad_sch}", "{schematic}"}:
        path, configured = inputs["schematic"]
        pattern = "*.kicad_sch"
    elif token in {"{kicad_pcb}", "{pcb}"}:
        path, configured = inputs["pcb"]
        pattern = "*.kicad_pcb"
    elif token in {"{workspace}", "{run_workspace}"}:
        return shlex.quote(str(workspace)), None
    elif token in {"{gerbers}", "{gerber_dir}"}:
        return shlex.quote(str(gerber_dir)), None
    else:
        return None, None

    if path is None:
        matches = _canonical_matches(_glob_matches(workspace, pattern))
        if matches:
            path = matches[0]
    if path is None:
        reason = f"no {('schematic' if 'sch' in token or 'schematic' in token else 'PCB')} file matches {pattern}"
        return None, reason
    if not path.exists():
        return shlex.quote(str(path)), f"input file does not exist: {path}"
    return shlex.quote(str(path)), None


def _resolve_shell_command(
    command: str,
    workspace: pathlib.Path,
    inputs: Mapping[str, tuple[pathlib.Path | None, bool]],
    gerber_dir: pathlib.Path,
) -> tuple[str, str | None]:
    command = _normalize_kicad_command(command)
    missing_reason: str | None = None
    tokens = [
        "{kicad_sch}", "{schematic}", "{kicad_pcb}", "{pcb}",
        "{workspace}", "{run_workspace}", "{gerbers}", "{gerber_dir}",
    ]
    for token in tokens:
        # Resolve only placeholders that the fixture command actually uses.
        # Otherwise a missing schematic would incorrectly fail a PCB-only
        # command (and vice versa) merely because we inspect all supported
        # placeholder forms in a common loop.
        if token not in command:
            continue
        replacement, reason = _placeholder_path(token, workspace, inputs, gerber_dir)
        if replacement is not None:
            command = command.replace(token, replacement)
        if reason and missing_reason is None:
            missing_reason = reason
    return command, missing_reason


def _command_timeout(check: Mapping[str, Any], default: int = DEFAULT_TIMEOUT_SECONDS) -> int:
    raw = check.get("timeout", default)
    try:
        return max(1, int(float(raw)))
    except (TypeError, ValueError):
        return default


