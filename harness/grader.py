# CLI and manifest/spec resolution


def _load_document(path: pathlib.Path) -> Any:
    text = path.read_text(encoding="utf-8")
    if path.suffix.lower() == ".json":
        return json.loads(text)
    if yaml is None:
        raise RuntimeError("PyYAML is required to read eval YAML files")
    return yaml.safe_load(text)


def _find_spec(spec_arg: str | None, run: Mapping[str, Any] | None, run_dir: pathlib.Path | None) -> pathlib.Path:
    candidates: list[pathlib.Path] = []
    if spec_arg:
        candidates.append(pathlib.Path(spec_arg))
    if run:
        for key in ("spec_path", "spec"):
            value = run.get(key)
            if isinstance(value, str):
                candidates.append(pathlib.Path(value))
    for candidate in list(candidates):
        if not candidate.is_absolute():
            if run_dir:
                candidates.append(run_dir / candidate)
            candidates.append(pathlib.Path.cwd() / candidate)
    for candidate in candidates:
        if candidate.exists() and candidate.is_file():
            return candidate.resolve()

    spec_id = run.get("spec_id") if run else None
    project_root = pathlib.Path(__file__).resolve().parent.parent
    search_dirs = [project_root / "evals"]
    if run_dir:
        search_dirs.extend([run_dir, run_dir.parent])
    for directory in search_dirs:
        if not directory.exists():
            continue
        for candidate in sorted([*directory.glob("*.yaml"), *directory.glob("*.yml")]):
            try:
                document = _load_document(candidate)
            except Exception:
                continue
            if spec_id is None or _mapping(document).get("id") == spec_id:
                return candidate.resolve()
    requested = spec_id or spec_arg or "unknown spec"
    raise FileNotFoundError(f"could not find eval spec: {requested}")


def _load_run(run_dir: pathlib.Path) -> dict[str, Any]:
    manifest_path = run_dir / "run.json"
    if not manifest_path.exists():
        return {}
    document = json.loads(manifest_path.read_text(encoding="utf-8"))
    return document if isinstance(document, dict) else {}


def _write_json(path: pathlib.Path, document: Mapping[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(json.dumps(document, indent=2, sort_keys=False) + "\n", encoding="utf-8")
    temporary.replace(path)


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", help="completed run output directory containing run.json")
    parser.add_argument("--spec", help="eval YAML/JSON spec; inferred from run.json when omitted")
    parser.add_argument("--workspace", help="completed artifact workspace; inferred from --run when omitted")
    parser.add_argument("--output", "--results", dest="output", help="results.json path (default: run/results.json or workspace/results.json)")
    # Retain old flags so existing Makefile/scripts do not fail while the
    # deterministic grader remains intentionally independent of an LLM judge.
    parser.add_argument("--no-llm", action="store_true", help="accepted for backward compatibility; no LLM is invoked")
    parser.add_argument("--cross-grade", action="store_true", help="accepted for backward compatibility; use cross_grade.py separately")
    parser.add_argument("--cross-agent", default=None, help=argparse.SUPPRESS)
    parser.add_argument("--cross-model", default=None, help=argparse.SUPPRESS)
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = _parser()
    args = parser.parse_args(argv)
    if not args.run and not args.workspace:
        parser.error("one of --run or --workspace is required")

    run_dir = pathlib.Path(args.run).resolve() if args.run else None
    run = _load_run(run_dir) if run_dir else {}

    if args.workspace:
        workspace = pathlib.Path(args.workspace).resolve()
    else:
        manifest_workspace = run.get("workspace")
        candidate = pathlib.Path(manifest_workspace) if isinstance(manifest_workspace, str) else pathlib.Path("workspace")
        if not candidate.is_absolute() and run_dir:
            candidate = run_dir / candidate
        workspace = candidate.resolve()

    output = pathlib.Path(args.output).resolve() if args.output else None
    if output is None:
        output = (run_dir / "results.json") if run_dir else (workspace / "results.json")

    try:
        spec_path = _find_spec(args.spec, run, run_dir)
        spec = _load_document(spec_path)
        if not isinstance(spec, Mapping):
            raise ValueError(f"eval spec must contain a mapping: {spec_path}")
        if not workspace.exists():
            # A missing workspace is still a structured failed result rather
            # than a traceback.  There is no input to grade, so all configured
            # contract checks are represented below by grading an empty path.
            workspace.mkdir(parents=True, exist_ok=True)
        result = grade_spec(spec, workspace)
        result["metadata"].update({
            "spec_path": str(spec_path),
            "run_id": run.get("run_id") if run else workspace.name,
            "agent": run.get("agent") if run else None,
            "model": run.get("model") if run else None,
            "output_path": str(output),
        })
        grading_cfg = spec.get("grading", {}) if isinstance(spec, dict) else {}
        spec_id_val = (run.get("spec_id") if run else None) or (spec.get("id") if isinstance(spec, dict) else None) or spec_path.stem
        result["spec_snapshot"] = {
            "spec_id": str(spec_id_val),
            "spec_version": spec.get("version") if isinstance(spec, dict) else None,
            "deterministic_checks": grading_cfg.get("deterministic", []),
            "llm_judge": grading_cfg.get("llm_judge") or None,
            "run_manifest": {
                "agent": run.get("agent") if run else None,
                "model": run.get("model") if run else None,
                "max_budget_usd": run.get("max_budget_usd") if run else None,
                "max_turns": run.get("max_turns") if run else None,
                "started_at": run.get("started_at") if run else None,
                "condition": run.get("condition") if run else None,
            },
            "snapshot_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        }
    except Exception as exc:
        # Setup/spec errors are represented in the same schema when an output
        # path is available.  This keeps automation consumable even when a
        # fixture is incomplete; missing-tool/file errors are handled at the
        # check level by grade_spec itself.
        result = {
            "schema_version": SCHEMA_VERSION,
            "metadata": {
                "schema_version": SCHEMA_VERSION,
                "workspace": str(workspace),
                "run_id": run.get("run_id") if run else workspace.name,
            },
            "checks": [{
                "name": "grader_setup",
                "type": "setup",
                "status": "failed",
                "pass": False,
                "passed": False,
                "command": None,
                "exit_code": None,
                "stdout": "",
                "stderr": "",
                "reason": str(exc),
                "artifacts": [],
            }],
            "artifacts": _collect_artifacts(workspace),
            "overall": {
                "status": "failed", "passed": False, "score": 0.0,
                "passed_checks": 0, "failed_checks": 1, "skipped_checks": 0, "total_checks": 1,
            },
            "status": "failed",
            "passed": False,
            "deterministic": [],
            "deterministic_score": 0.0,
            "final_score": 0.0,
        }

    _write_json(output, result)
    if run_dir:
        # Upgrade 3: co-located grader result under grades/deterministic/
        _write_json(run_dir / "grades" / "deterministic" / "grade.json", result)
        # Index manifest at run root (grade.json); results.json remains the legacy alias.
        _meta = result.get("metadata", {})
        _snap = result.get("spec_snapshot") or {}
        _manifest = {
            "schema_version": "1.0.0",
            "run_id": _meta.get("run_id") or run_dir.name,
            "spec_id": _snap.get("spec_id") or _meta.get("run_id") or run_dir.name,
            "graded_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
            "graders": ["deterministic"],
            "paths": {"deterministic": "grades/deterministic/grade.json"},
            "passed": result.get("passed", False),
            "final_score": result.get("final_score", 0.0),
            "deterministic_score": result.get("deterministic_score", 0.0),
            "spec_snapshot": _snap or None,
        }
        _write_json(run_dir / "grade.json", _manifest)
    failed = result["overall"]["failed_checks"] if "overall" in result else 1
    print(f"[grader] wrote {output}")
    print(f"[grader] status={result.get('status', 'failed')} failed_checks={failed}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
