# Check execution and result construction


def _check_record(
    name: str,
    check_type: str,
    status: str,
    *,
    command: str | None = None,
    configured_command: str | None = None,
    exit_code: int | None = None,
    stdout: str = "",
    stderr: str = "",
    reason: str | None = None,
    artifacts: Iterable[str] = (),
    details: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    passed = status == "passed"
    record: dict[str, Any] = {
        "name": name,
        "type": check_type,
        "status": status,
        "pass": passed,
        "passed": passed,
        "command": command,
        "exit_code": exit_code,
        "stdout": stdout,
        "stderr": stderr,
        "reason": reason or ("check passed" if passed else "check failed"),
        "artifacts": sorted(set(artifacts)),
    }
    if configured_command is not None and configured_command != command:
        record["configured_command"] = configured_command
    if details:
        record["details"] = dict(details)
    return record


def _readable_process_output(value: str | bytes | None) -> str:
    if value is None:
        return ""
    if isinstance(value, bytes):
        return value[:MAX_OUTPUT_BYTES].decode("utf-8", errors="replace")
    # Do not silently discard normal tool output.  The limit only protects the
    # results file from a pathological CLI that emits unbounded diagnostics.
    return value[:MAX_OUTPUT_BYTES]


def _run_argv(argv: list[str], workspace: pathlib.Path, timeout: int) -> dict[str, Any]:
    command = shlex.join(argv)
    try:
        proc = subprocess.run(
            argv,
            cwd=str(workspace),
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )
        return {
            "command": command,
            "exit_code": proc.returncode,
            "stdout": _readable_process_output(proc.stdout),
            "stderr": _readable_process_output(proc.stderr),
            "reason": None,
        }
    except FileNotFoundError as exc:
        return {
            "command": command,
            "exit_code": None,
            "stdout": "",
            "stderr": "",
            "reason": f"required tool is not installed or not on PATH: {exc.filename or argv[0]}",
        }
    except subprocess.TimeoutExpired as exc:
        return {
            "command": command,
            "exit_code": 124,
            "stdout": _readable_process_output(exc.stdout),
            "stderr": _readable_process_output(exc.stderr),
            "reason": f"command timed out after {timeout} seconds",
        }
    except OSError as exc:
        return {
            "command": command,
            "exit_code": None,
            "stdout": "",
            "stderr": "",
            "reason": f"could not execute command: {exc}",
        }


def _run_shell(command: str, workspace: pathlib.Path, timeout: int) -> dict[str, Any]:
    try:
        proc = subprocess.run(
            command,
            shell=True,
            cwd=str(workspace),
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )
        reason = None
        if proc.returncode == 127:
            reason = "command or required tool was not found (shell exit code 127)"
        return {
            "command": command,
            "exit_code": proc.returncode,
            "stdout": _readable_process_output(proc.stdout),
            "stderr": _readable_process_output(proc.stderr),
            "reason": reason,
        }
    except subprocess.TimeoutExpired as exc:
        return {
            "command": command,
            "exit_code": 124,
            "stdout": _readable_process_output(exc.stdout),
            "stderr": _readable_process_output(exc.stderr),
            "reason": f"command timed out after {timeout} seconds",
        }
    except OSError as exc:
        return {
            "command": command,
            "exit_code": None,
            "stdout": "",
            "stderr": "",
            "reason": f"could not execute command: {exc}",
        }


def _run_required_files(
    patterns: list[str], workspace: pathlib.Path, name: str = "required_files"
) -> dict[str, Any]:
    details: list[dict[str, Any]] = []
    matched_artifacts: list[str] = []
    missing: list[str] = []
    for pattern in patterns:
        matches = _glob_matches(workspace, pattern)
        # A directory output such as ``gerbers/`` is a valid required artifact
        # only when the directory itself exists and is a directory.
        matches = [match for match in matches if match.exists()]
        files = [match for match in matches if match.is_file() or match.is_dir()]
        artifact_paths = [_safe_relpath(match, workspace) for match in files]
        matched_artifacts.extend(artifact_paths)
        details.append({"pattern": pattern, "matched": sorted(artifact_paths), "present": bool(files)})
        if not files:
            missing.append(pattern)
    if missing:
        reason = "required files are missing: " + ", ".join(missing)
        return _check_record(
            name,
            "required_files",
            "failed",
            reason=reason,
            artifacts=matched_artifacts,
            details={"patterns": details},
        )
    return _check_record(
        name,
        "required_files",
        "passed",
        reason="all required file patterns are present",
        artifacts=matched_artifacts,
        details={"patterns": details},
    )


def _run_kicad_check(
    name: str,
    check_type: str,
    input_path: pathlib.Path | None,
    configured: bool,
    workspace: pathlib.Path,
    gerber_dir: pathlib.Path,
    timeout: int,
) -> dict[str, Any]:
    if not configured:
        return _check_record(
            name,
            check_type,
            "skipped",
            reason=f"no {('schematic' if check_type == 'erc' else 'PCB')} input configured",
        )
    if input_path is None:
        label = "schematic" if check_type == "erc" else "PCB"
        return _check_record(
            name,
            check_type,
            "failed",
            reason=f"fixture specifies a {label} input, but it could not be resolved",
        )
    if not input_path.exists():
        label = "schematic" if check_type == "erc" else "PCB"
        expected_command = [
            "kicad-cli", "sch", "erc" if check_type == "erc" else "drc", str(input_path),
            "--exit-code-violations", "--format", "json",
        ]
        return _check_record(
            name,
            check_type,
            "failed",
            command=shlex.join(expected_command),
            reason=f"{label} input file does not exist: {input_path}",
            artifacts=[_safe_relpath(input_path, workspace)],
        )

    subcommand = ["sch", "erc"] if check_type == "erc" else ["pcb", "drc"]
    argv = ["kicad-cli", *subcommand, str(input_path), "--exit-code-violations", "--format", "json"]
    if check_type == "gerber_export":
        raise ValueError("gerber export is not a KiCad rule check")
    process = _run_argv(argv, workspace, timeout)
    if process["reason"]:
        reason = process["reason"]
    elif process["exit_code"] == 0:
        reason = f"KiCad {check_type.upper()} completed with no reported violations"
    else:
        reason = f"KiCad {check_type.upper()} exited with code {process['exit_code']}"
    return _check_record(
        name,
        check_type,
        "passed" if process["exit_code"] == 0 else "failed",
        command=process["command"],
        exit_code=process["exit_code"],
        stdout=process["stdout"],
        stderr=process["stderr"],
        reason=reason,
        artifacts=[_safe_relpath(input_path, workspace)],
    )


def _run_gerber_export(
    pcb_path: pathlib.Path | None,
    configured: bool,
    workspace: pathlib.Path,
    gerber_dir: pathlib.Path,
    timeout: int,
    name: str = "gerber_export",
) -> dict[str, Any]:
    if not configured:
        return _check_record(name, "gerber_export", "skipped", reason="no PCB input configured")
    if pcb_path is None:
        return _check_record(
            name,
            "gerber_export",
            "failed",
            reason="fixture specifies a PCB input, but it could not be resolved",
        )
    if not pcb_path.exists():
        command = shlex.join([
            "kicad-cli", "pcb", "export", "gerbers", str(pcb_path), "--output", str(gerber_dir)
        ])
        return _check_record(
            name,
            "gerber_export",
            "failed",
            command=command,
            reason=f"PCB input file does not exist: {pcb_path}",
            artifacts=[_safe_relpath(pcb_path, workspace)],
        )

    gerber_dir.mkdir(parents=True, exist_ok=True)
    argv = ["kicad-cli", "pcb", "export", "gerbers", str(pcb_path), "--output", str(gerber_dir)]
    process = _run_argv(argv, workspace, timeout)
    exported = [
        _safe_relpath(path, workspace)
        for path in sorted(gerber_dir.rglob("*"))
        if path.is_file()
    ] if gerber_dir.exists() else []
    if process["reason"]:
        reason = process["reason"]
    elif process["exit_code"] == 0:
        reason = "KiCad Gerber export completed successfully"
    else:
        reason = f"KiCad Gerber export exited with code {process['exit_code']}"
    return _check_record(
        name,
        "gerber_export",
        "passed" if process["exit_code"] == 0 else "failed",
        command=process["command"],
        exit_code=process["exit_code"],
        stdout=process["stdout"],
        stderr=process["stderr"],
        reason=reason,
        artifacts=[_safe_relpath(pcb_path, workspace), *exported],
        details={"output_directory": _safe_relpath(gerber_dir, workspace), "exported_artifacts": exported},
    )


def _run_fixture_check(
    check: Mapping[str, Any],
    workspace: pathlib.Path,
    inputs: Mapping[str, tuple[pathlib.Path | None, bool]],
    gerber_dir: pathlib.Path,
    index: int,
) -> dict[str, Any]:
    name = str(check.get("name") or f"deterministic_{index}")
    check_type = _classify_check(check)
    if check_type == "required_files":
        raw = check.get("files", check.get("paths", check.get("required_files", check.get("path"))))
        patterns: list[str] = []
        if isinstance(raw, str):
            patterns = [raw]
        elif isinstance(raw, (list, tuple)):
            patterns = [str(item) for item in raw]
        if patterns:
            return _run_required_files(patterns, workspace, name=name)

    raw_command = check.get("command", check.get("check"))
    if raw_command is None and check_type in {"erc", "drc", "gerber_export"}:
        # Compact fixtures may declare a typed KiCad check and its input
        # without spelling out the command.  Generate the same verified
        # KiCad invocation used for the automatic checks.
        input_value = check.get("input", check.get("file", check.get("path")))
        if check_type == "gerber_export":
            if input_value is None:
                input_path, configured = inputs["pcb"]
            else:
                input_path, configured = _first_existing(input_value, workspace)
            return _run_gerber_export(input_path, configured, workspace, gerber_dir, _command_timeout(check), name=name)
        kind = "schematic" if check_type == "erc" else "pcb"
        if input_value is None:
            input_path, configured = inputs[kind]
        else:
            input_path, configured = _first_existing(input_value, workspace)
        return _run_kicad_check(name, check_type, input_path, configured, workspace, gerber_dir, _command_timeout(check))
    if raw_command is None:
        return _check_record(
            name,
            check_type,
            "failed",
            reason="fixture check has neither a command nor a file pattern",
        )
    if not isinstance(raw_command, str):
        return _check_record(name, check_type, "failed", reason="fixture command must be a string")

    command, missing_reason = _resolve_shell_command(raw_command, workspace, inputs, gerber_dir)
    if missing_reason:
        return _check_record(
            name,
            check_type,
            "failed",
            command=command,
            configured_command=raw_command,
            reason=missing_reason,
        )
    process = _run_shell(command, workspace, _command_timeout(check))
    if process["reason"]:
        reason = process["reason"]
    elif process["exit_code"] == 0:
        reason = "fixture command completed successfully"
    else:
        reason = f"fixture command exited with code {process['exit_code']}"
    return _check_record(
        name,
        check_type,
        "passed" if process["exit_code"] == 0 else "failed",
        command=process["command"],
        configured_command=raw_command,
        exit_code=process["exit_code"],
        stdout=process["stdout"],
        stderr=process["stderr"],
        reason=reason,
    )


def find_files(workspace: pathlib.Path, pattern: str) -> list[pathlib.Path]:
    """Backward-compatible canonical glob helper used by older callers."""
    return _canonical_matches(_glob_matches(pathlib.Path(workspace), pattern))


def run_deterministic(check: Mapping[str, Any], workspace: pathlib.Path) -> dict[str, Any]:
    """Backward-compatible single-check entry point.

    New callers should use :func:`grade_spec`, which can resolve fixture
    inputs and append the required core checks.  This helper preserves the
    original harness API for scripts that execute one YAML check directly.
    """
    root = pathlib.Path(workspace).resolve()
    spec = {"grading": {"deterministic": [check]}}
    inputs = _resolve_inputs(spec, root)
    return _run_fixture_check(check, root, inputs, root / "gerbers", 1)


def find_spec_for_run(run: Mapping[str, Any]) -> pathlib.Path | None:
    """Backward-compatible spec lookup; return ``None`` when unresolved."""
    try:
        return _find_spec(None, run, None)
    except (FileNotFoundError, OSError, ValueError):
        return None


def _has_explicit_type(checks: list[Mapping[str, Any]], wanted: str) -> bool:
    for check in checks:
        typ = _classify_check(check)
        if wanted == "gerber_export":
            # A named shell presence check is not the export command.
            command = str(check.get("command", ""))
            declared = str(check.get("type", check.get("kind", ""))).strip().lower().replace("-", "_")
            if typ == wanted and ("pcb export gerbers" in command or declared in {"gerber", "gerbers", "gerber_export", "pcb_gerbers"}):
                return True
        elif wanted in {"erc", "drc"}:
            declared = str(check.get("type", check.get("kind", ""))).strip().lower().replace("-", "_")
            command = str(check.get("command", check.get("check", ""))).lower()
            if declared in {wanted, "schematic_erc" if wanted == "erc" else "pcb_drc"}:
                return True
            if wanted == "erc" and "kicad-cli" in command and "sch erc" in command:
                return True
            if wanted == "drc" and "kicad-cli" in command and "pcb drc" in command:
                return True
        elif typ == wanted:
            return True
    return False


def _gerber_directory(spec: Mapping[str, Any], workspace: pathlib.Path) -> pathlib.Path:
    containers = [
        _mapping(spec.get("outputs")),
        _mapping(spec.get("inputs")),
        _mapping(spec.get("fixture")),
        _mapping(spec.get("fixtures")),
        _mapping(_mapping(spec.get("grading")).get("fixture")),
        _mapping(spec.get("grading")),
    ]
    for container in containers:
        for key in ("gerber_dir", "gerbers_dir", "gerber_output", "output_directory"):
            value = container.get(key)
            if isinstance(value, str):
                path = pathlib.Path(value)
                return path if path.is_absolute() else workspace / path
    return workspace / "gerbers"


def _collect_artifacts(workspace: pathlib.Path) -> list[str]:
    if not workspace.exists():
        return []
    paths: list[str] = []
    for path in sorted(workspace.rglob("*")):
        if path.is_file() and "__pycache__" not in path.parts and path.name not in {"results.json", "grade.json"}:
            paths.append(_safe_relpath(path, workspace))
    return paths


def grade_spec(spec: Mapping[str, Any], workspace: pathlib.Path) -> dict[str, Any]:
    """Grade *workspace* according to *spec* and return the stable result doc."""
    workspace = workspace.resolve()
    inputs = _resolve_inputs(spec, workspace)
    gerber_dir = _gerber_directory(spec, workspace)
    fixture_checks = _deterministic_specs(spec)
    checks: list[dict[str, Any]] = []

    # Run fixture-defined checks in their declared order.  This preserves the
    # spec as the contract while the generated checks below fill any gaps.
    for index, check in enumerate(fixture_checks, start=1):
        checks.append(_run_fixture_check(check, workspace, inputs, gerber_dir, index))

    # Always represent the core check types.  Explicit KiCad commands are not
    # duplicated; shell presence checks do not replace the export command.
    if not _has_explicit_type(fixture_checks, "erc"):
        path, configured = inputs["schematic"]
        checks.append(_run_kicad_check("schematic_erc", "erc", path, configured, workspace, gerber_dir, DEFAULT_TIMEOUT_SECONDS))
    if not _has_explicit_type(fixture_checks, "drc"):
        path, configured = inputs["pcb"]
        checks.append(_run_kicad_check("pcb_drc", "drc", path, configured, workspace, gerber_dir, DEFAULT_TIMEOUT_SECONDS))
    if not _has_explicit_type(fixture_checks, "gerber_export"):
        path, configured = inputs["pcb"]
        checks.append(_run_gerber_export(path, configured, workspace, gerber_dir, DEFAULT_TIMEOUT_SECONDS))

    # The output list is the fixture-defined artifact contract.  Run it after
    # export so a successful exporter can satisfy gerber output patterns.
    patterns = _output_patterns(spec)
    checks.append(_run_required_files(patterns, workspace))

    passed_count = sum(1 for check in checks if check["status"] == "passed")
    failed_count = sum(1 for check in checks if check["status"] == "failed")
    skipped_count = sum(1 for check in checks if check["status"] == "skipped")
    evaluated_count = passed_count + failed_count
    score = passed_count / evaluated_count if evaluated_count else 1.0
    overall_status = "failed" if failed_count else "passed"
    artifacts = _collect_artifacts(workspace)

    overall = {
        "status": overall_status,
        "passed": overall_status == "passed",
        "score": score,
        "passed_checks": passed_count,
        "failed_checks": failed_count,
        "skipped_checks": skipped_count,
        "total_checks": len(checks),
    }
    metadata = {
        "schema_version": SCHEMA_VERSION,
        "spec_id": spec.get("id"),
        "spec_version": spec.get("version"),
        "workspace": str(workspace),
        "deterministic": True,
    }
    return {
        "schema_version": SCHEMA_VERSION,
        "metadata": metadata,
        "checks": checks,
        "artifacts": artifacts,
        "overall": overall,
        # Compatibility fields for the existing static site/aggregate tooling.
        "status": overall_status,
        "passed": overall_status == "passed",
        "deterministic": checks,
        "deterministic_score": score,
        "final_score": score,
    }


